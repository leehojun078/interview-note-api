package com.hojun.interviewnote.interviewnoteapi.service.ai.prompt

import org.springframework.stereotype.Service

/**
 * 종합 평가용 프롬프트 생성기
 *
 * Phase 2 리팩토링: PromptBuilder에서 분리
 * 역할: 면접 종료 시 종합 평가 프롬프트 생성
 */
@Service
class EvaluationPromptBuilder {

    /**
     * 종합 평가 프롬프트 생성
     *
     * Phase 8A 개선: 예시 기반 + 질문 유도
     *
     * @param jobField 직무 분야
     * @param companyName 회사명 (선택)
     * @param jobTitle 직무명 (선택)
     * @param allUserAnswers 모든 사용자 답변
     * @return 종합 평가 프롬프트
     */
    fun buildFinalEvaluationPrompt(
        jobField: String,
        companyName: String?,
        jobTitle: String?,
        allUserAnswers: String
    ): String {
        val interviewType = if (companyName != null && jobTitle != null) {
            "공고 기반 (${companyName} - ${jobTitle})"
        } else {
            "직무 기반 (${jobField})"
        }

        return """
            당신은 ${jobField} 분야의 면접 평가 전문가입니다.
            전체 면접 대화를 기반으로 종합 평가를 작성하세요.

            면접 유형: $interviewType
            직무: $jobField

            === 지원자의 모든 답변 ===
            $allUserAnswers

            === ✅ 좋은 예시 (550자 - 반드시 이 수준으로 작성) ===

            "지원자는 백엔드 개발자로서의 기본 소양과 열정을 충분히 보여주었습니다.
            전반적으로 답변의 구조가 명확하고, 자신의 경험을 체계적으로 전달하려는
            노력이 돋보였습니다. 특히 기술적 개념에 대한 이해도가 높았으며, 실무
            경험을 바탕으로 한 실질적인 답변이 인상적이었습니다.

            가장 우수했던 부분은 REST API 설계 경험에 대한 답변이었습니다.
            단순히 RESTful 원칙을 나열하는 것이 아니라, 실제 프로젝트에서 겪었던
            버전 관리 이슈와 이를 해결하기 위한 URI 설계 개선 과정을 구체적으로
            설명했습니다. 특히 하위 호환성을 유지한 경험은 실무 감각을 잘 보여줍니다.

            반면, 팀 협업 경험에 대한 답변이 다소 추상적이었습니다. '열심히 협력했다'와
            같은 표현보다는, 구체적으로 어떤 상황에서 어떤 방식으로 소통했는지
            STAR 기법을 활용하면 더 설득력이 높아질 것입니다.

            전반적으로 기술적 역량은 우수하지만, 답변의 깊이를 더하고 팀워크 관련
            사례를 보강한다면 더욱 경쟁력 있는 지원자가 될 것입니다."

            === ❌ 나쁜 예시 (150자 - 절대 이렇게 쓰지 마세요!) ===

            "지원자는 열정이 있고 기본기가 있습니다. 하지만 좀 더 구체적인
            답변이 필요하며, 협업 경험을 보강하면 좋겠습니다. 전반적으로
            괜찮은 수준입니다."
            → 이런 짧고 추상적인 피드백은 금지!

            === 📝 작성 가이드: 다음 질문에 모두 답변하세요 ===

            overallFeedback을 작성할 때, 다음 7가지 질문에 답변하면서 자연스럽게
            하나의 완결된 피드백으로 작성하세요. (목표: 500-700자)

            1. 이 지원자의 첫인상은 어떠했나요? 전체 답변의 품질은? (3-4문장)
            2. 전체 답변에서 가장 인상 깊었던 강점은 무엇인가요? (4-5문장)
            3. 구체적으로 어떤 답변이 우수했고, 왜 그렇게 평가하나요? (4-5문장)
            4. 반대로 가장 아쉬웠던 부분은 무엇인가요? (4-5문장)
            5. 지원자가 보완해야 할 구체적인 내용은 무엇인가요? (4-5문장)
            6. 다음 면접을 위해 어떤 준비를 해야 할까요? (3-4문장)
            7. 이 지원자를 한 문장으로 평가한다면? (1-2문장)

            **작성 팁**:
            - 각 질문에 최소 80-120자씩 할애하세요
            - "예를 들어", "구체적으로", "특히" 같은 상세화 표현을 활용하세요
            - 실제 답변 내용을 인용하거나 요약하여 근거를 제시하세요
            - 억지로 글자수를 채우지 말고, 실제 관찰한 내용을 상세히 서술하세요

            === 종합 평가 작성 규칙 ===

            1. **overallFeedback** (500-700자 필수):
               - 위 7가지 질문에 모두 답변
               - 위 "좋은 예시"처럼 구체적이고 상세하게 작성

            2. **keyStrengths** (0-5개):
               - 평균 4.0+: 4-5개 | 3.0-3.9: 2-3개 | 2.0-2.9: 1-2개 | 2.0 미만: 0-1개
               - **중요**: 실제로 두드러진 강점만 작성, 억지로 만들지 마세요

            3. **keyImprovements** (1-5개, 최소 1개 필수):
               - 평균 4.0+: 1-2개 | 3.0-3.9: 2-3개 | 2.0-2.9: 3-4개 | 2.0 미만: 4-5개
               - **중요**: 구체적이고 실질적인 개선 방향 제시

            4. **averageScore** (1.0-5.0):
               - 모든 답변의 평균 점수 계산
               - **주의**: 첫 답변(자기소개)는 관대하게 평가, 나머지는 엄격하게

            5. **recommendation**:
               - "합격 추천 + 근거" / "보류 + 근거" / "불합격 + 근거"

            === 엄격한 평가 기준 ===

            **짧은 답변 처리**:
            - 20자 미만: 모든 점수 1점, "답변이 너무 짧습니다" 코멘트
            - 20-50자: 구체성 1-2점, "좀 더 구체적으로 설명해주세요" 코멘트
            - 50자 이상: 정상 평가

            **자기소개 예외** (첫 답변만):
            - 첫 답변(자기소개)은 50자 이상이면 관대하게 평가 (3-4점)
            - 이름, 경력, 관심사만 언급해도 괜찮음

            **나쁜 답변 예시와 점수**:
            - "안녕하세요" (10자) → 모든 항목 1점
            - "열심히 노력했습니다" (추상적) → logic: 2, specificity: 1, delivery: 2
            - "여기는 여기는..." (반복) → 모든 항목 1점

            **좋은 답변 예시와 점수**:
            - 구체적 사례 + 수치 + 기술 스택 → logic: 4-5, specificity: 4-5
            - STAR 기법 활용 → logic: 4-5, delivery: 4-5
            - 명확한 구조 + 깊이 있는 분석 → 모든 항목 4-5점

            === 출력 형식 (JSON) ===
            {
              "overallFeedback": "종합 피드백 (500-700자, 위 7가지 질문에 모두 답변)",
              "keyStrengths": ["강점1", "강점2", ...],
              "keyImprovements": ["개선점1", "개선점2", ...],
              "averageScore": 3.2,
              "recommendation": "보류 - 기술적 깊이를 더하면 합격 가능"
            }

            **중요**:
            - 반드시 JSON 형식으로만 응답하세요
            - overallFeedback은 최소 500자 이상 작성하세요
            - 위 "좋은 예시"를 참고하여 비슷한 수준으로 작성하세요
        """.trimIndent()
    }
}
